    private void setupRoleBasedAccess() {
        // Update header info
        String welcomeName = authService.getUserLoggedIn().getNamaPengguna();
        String role = authService.getUserLoggedIn().getPeran();

        lblWelcome.setText("Selamat Datang, " + welcomeName);
        lblRole.setText("Role: " + role.toUpperCase());
        lblAccessInfo.setText(getAccessInfo());

        // Set window title
        setTitle("Cafe Management System - " + role.toUpperCase());

        System.out.println("🔐 User Role: " + authService.getUserRole());

        // Setup buttons berdasarkan role
        setupMenuButtons();

    }

    private String getAccessInfo() {
        if (authService.isKasir()) {
            return "Akses: Transaksi & Lihat Menu";
        } else if (authService.isManager()) {
            return "Akses: Transaksi, Menu, Stok & Laporan";
        } else if (authService.isAdmin() || authService.isOwner()) {
            return "Akses: Full System";
        }
        return "Akses: Terbatas";
    }

    private void setupMenuButtons() {

         btnKelolaStok.setVisible(authService.canManageStok());
        btnLaporan.setVisible(authService.canViewReports());
        btnKelolaMenu.setVisible(authService.canManageMenu());
        btnKelolaUser.setVisible(authService.canManageUsers());

    }
